train_file_path = "train-data.tsv"
test_file_path = "valid-data.tsv"

from tensorflow.keras import layers
# Load and prepare data
train_df = pd.read_csv(train_file_path, sep='\t', header=None, names=['label','text'])
valid_df = pd.read_csv(test_file_path, sep='\t', header=None, names=['label','text'])

train_df['label_num'] = train_df['label'].map({'ham':0, 'spam':1})
valid_df['label_num'] = valid_df['label'].map({'ham':0, 'spam':1})

train_texts = train_df['text'].astype(str).values
train_labels = train_df['label_num'].values
valid_texts = valid_df['text'].astype(str).values
valid_labels = valid_df['label_num'].values

# Text vectorization - converts strings to integer sequences
VOCAB_SIZE = 10000
SEQUENCE_LENGTH = 100
vectorize_layer = layers.TextVectorization(
    max_tokens=VOCAB_SIZE,
    output_mode='int',
    output_sequence_length=SEQUENCE_LENGTH
)
vectorize_layer.adapt(train_texts)

# Model: Embedding + Bidirectional LSTM + Dense
model = keras.Sequential([
    vectorize_layer,
    layers.Embedding(VOCAB_SIZE, 16, mask_zero=True),
    layers.Bidirectional(layers.LSTM(32)),
    layers.Dense(32, activation='relu'),
    layers.Dropout(0.3),
    layers.Dense(1, activation='sigmoid')
])

model.compile(loss='binary_crossentropy', optimizer='adam', metrics=['accuracy'])

# Train - account for imbalance: 3619 ham vs 560 spam (~1:6.46)
history = model.fit(
    train_texts, train_labels,
    epochs=12,
    batch_size=32,
    validation_data=(valid_texts, valid_labels),
    class_weight={0: 1, 1: 6.46},
    verbose=1
)

# function to predict messages based on model
# (should return list containing prediction and label, ex. [0.008318834938108921, 'ham'])
def predict_message(pred_text):
    prediction = model.predict(tf.constant([pred_text]), verbose=0)[0][0]
    label = "spam" if prediction > 0.5 else "ham"
    return [float(prediction), label]

pred_text = "how are you doing today?"
prediction = predict_message(pred_text)
print(prediction)

